export const RECENT_EMOJI_LIMIT = 32;

export function searchEmojis(query: string): EmojiEntry[] {
  const needle = query.trim().toLocaleLowerCase('uk-UA');
  if (!needle) return [];
  const seen = new Set<string>();
  const matches: EmojiEntry[] = [];
  for (const item of EMOJI_GROUPS.flatMap((item) => item.emojis)) {
    const haystack = `${item.name} ${item.char}`.toLocaleLowerCase('uk-UA');
    if (haystack.includes(needle) && !seen.has(item.char)) {
      seen.add(item.char);
      matches.push(item);
    }
  }
  return matches.slice(0, 96);
}
